#!/usr/bin/env node
/**
 * Generates the Storybook stories for the page templates and flows from
 * design-kit/templates/templates.json — one story per captured page, one per flow.
 * There is a single source for both the kit and Storybook, so they cannot disagree.
 *
 *   node scripts/build-template-stories.mjs   (part of npm run build:kit)
 */
import { readFileSync, writeFileSync, mkdirSync, readdirSync, rmSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'src/templates/generated');
const { sites } = JSON.parse(readFileSync(join(ROOT, 'design-kit/templates/templates.json'), 'utf8'));

const pascal = (n) => n.replace(/(^|[-_/])(\w)/g, (_, __, c) => c.toUpperCase()).replace(/[^A-Za-z0-9]/g, '');
const titleCase = (n) => n.replace(/-/g, ' ').replace(/^./, (c) => c.toUpperCase());

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });

const argTypes = `  argTypes: {
    device: { control: 'inline-radio', options: ['desktop', 'mobile'], description: 'Desktop renders at 1440px, mobile at 390px; the frame is scaled to fit.' },
    site: { table: { disable: true } },
    name: { table: { disable: true } },
    label: { table: { disable: true } },
    path: { table: { disable: true } },
    devices: { table: { disable: true } },
    capturedAt: { table: { disable: true } },
    origin: { table: { disable: true } },
  },`;

let pageCount = 0;
let flowCount = 0;

for (const [site, data] of Object.entries(sites)) {
  const names = Object.keys(data.pages);
  if (!names.length) continue;

  const pageStory = (name) => {
    const p = data.pages[name];
    return `export const ${pascal(name)}: Story = {
  name: ${JSON.stringify(p.label ?? titleCase(name))},
  args: ${JSON.stringify({ site, name, label: p.label ?? titleCase(name), path: p.path, devices: p.devices, ...(p.capturedAt ? { capturedAt: p.capturedAt } : {}) }, null, 2).replace(/\n/g, '\n  ')},
};`;
  };

  writeFileSync(
    join(OUT, `${pascal(site)}Pages.stories.tsx`),
    `/* GENERATED by scripts/build-template-stories.mjs — do not edit. */
import type { Meta, StoryObj } from '@storybook/react';
import { PageFrame } from '../PageFrame';

const meta: Meta<typeof PageFrame> = {
  title: 'Pages/${data.label}',
  component: PageFrame,
  parameters: {
    layout: 'fullscreen',
    docs: { description: { component: ${JSON.stringify(`${data.label} pages, captured from ${data.source}. Each story renders the exact file in \`design-kit/templates/${site}/\`, so Storybook and the design kit always match. Links between captured pages work inside the frame — click straight through the journey. Forms are inert: nothing can be submitted.`)} } },
  },
${argTypes}
  args: { device: 'desktop' },
};
export default meta;

type Story = StoryObj<typeof PageFrame>;

${names.map(pageStory).join('\n\n')}
`,
  );
  pageCount += names.length;

  const flows = (data.flows ?? [])
    .map((f) => ({ ...f, steps: f.steps.filter((s) => data.pages[s]) }))
    .filter((f) => f.steps.length > 1);
  if (!flows.length) continue;

  const flowStory = (f) => `export const ${pascal(f.name)}: Story = {
  name: ${JSON.stringify(f.name)},
  args: ${JSON.stringify(
    {
      site,
      flow: f.name,
      steps: f.steps.map((s) => ({ name: s, label: data.pages[s].label ?? titleCase(s), path: data.pages[s].path, devices: data.pages[s].devices, ...(data.pages[s].capturedAt ? { capturedAt: data.pages[s].capturedAt } : {}) })),
    },
    null,
    2,
  ).replace(/\n/g, '\n  ')},
};`;

  writeFileSync(
    join(OUT, `${pascal(site)}Flows.stories.tsx`),
    `/* GENERATED by scripts/build-template-stories.mjs — do not edit. */
import type { Meta, StoryObj } from '@storybook/react';
import { FlowFrame } from '../FlowFrame';

const meta: Meta<typeof FlowFrame> = {
  title: 'Flows/${data.label}',
  component: FlowFrame,
  parameters: {
    layout: 'fullscreen',
    docs: { description: { component: ${JSON.stringify(`End-to-end ${data.label} journeys through the captured pages. Use the step buttons, or click the page's own links — both move through the real markup.`)} } },
  },
  argTypes: {
    device: { control: 'inline-radio', options: ['desktop', 'mobile'] },
    site: { table: { disable: true } },
    flow: { table: { disable: true } },
    steps: { table: { disable: true } },
  },
  args: { device: 'desktop' },
};
export default meta;

type Story = StoryObj<typeof FlowFrame>;

${flows.map(flowStory).join('\n\n')}
`,
  );
  flowCount += flows.length;
}

console.log(`stories    ${pageCount} pages, ${flowCount} flows -> ${readdirSync(OUT).length} files in src/templates/generated/`);
